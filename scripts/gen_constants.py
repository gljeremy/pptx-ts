"""Generate src/opc/constants.ts from python-pptx's pptx/opc/constants.py.

Usage: py -I scripts/gen_constants.py <python-pptx checkout> src/opc/constants.ts
"""
import ast
import json
import sys

src = open(sys.argv[1] + "/src/pptx/opc/constants.py", encoding="utf-8").read()
tree = ast.parse(src)
out = ["// GENERATED by scripts/gen_constants.py from python-pptx's pptx/opc/constants.py. Do not edit.",
       "// Constant values related to the Open Packaging Convention: content types, namespaces,",
       "// relationship target modes and relationship types.", ""]
for node in tree.body:
    if not isinstance(node, ast.ClassDef):
        continue
    doc = ast.get_docstring(node)
    if doc:
        out.append(f"/** {doc.splitlines()[0]} */")
    out.append(f"export const {node.name} = {{")
    for st in node.body:
        if isinstance(st, ast.Assign) and isinstance(st.value, ast.Constant):
            out.append(f"  {st.targets[0].id}: {json.dumps(st.value.value)},")
    out.append("} as const;")
    out.append("")
out.append("export const CT = CONTENT_TYPE;")
out.append("export const NS = NAMESPACE;")
out.append("export const RTM = RELATIONSHIP_TARGET_MODE;")
out.append("export const RT = RELATIONSHIP_TYPE;")
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
