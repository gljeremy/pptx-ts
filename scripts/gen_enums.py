"""Generate src/enum/{action,chart,dml,lang,shapes,text}.ts from python-pptx's pptx.enum package.

Members are read by importing the enums (python-pptx must be importable, e.g. the venv
that has it installed in editable mode), so values, XML mappings, docstrings and aliases
are exactly upstream's.

Usage: python scripts/gen_enums.py src/enum
"""
import importlib
import inspect
import json
import sys

from pptx.enum.base import BaseEnum, BaseXmlEnum

MODULES = ["action", "chart", "dml", "lang", "shapes", "text"]

# hand-written members appended to a module (enums that aren't BaseEnum/BaseXmlEnum)
EXTRA = {
    "shapes": '''
/** A member of `PROG_ID`: the progId and icon used for an embedded OLE object. */
export class ProgIdMember {
  declare readonly name: string;
  declare readonly value: string;
  declare readonly progId: string;
  declare readonly iconFilename: string;
  declare readonly width: number;
  declare readonly height: number;

  constructor(value: string, progId: string, iconFilename: string, width: number, height: number) {
    Object.defineProperties(this, {
      name: { value, enumerable: true },
      value: { value, enumerable: true },
      progId: { value: progId, enumerable: true },
      iconFilename: { value: iconFilename, enumerable: true },
      width: { value: width, enumerable: true },
      height: { value: height, enumerable: true },
    });
    Object.freeze(this);
  }

  toString(): string {
    return `PROG_ID.${this.name}`;
  }

  __repr__(): string {
    return `<PROG_ID.${this.name}: '${this.value}'>`;
  }
}

/**
 * One-off enum of progId values: the type of an OLE object in terms of the program used to
 * open it. Pass a member to `SlideShapes.addOleObject()` for an Office file type.
 */
const PROG_ID_MEMBERS = {
  /** `progId` for an embedded Word 2007+ (.docx) document. */
  DOCX: new ProgIdMember("DOCX", "Word.Document.12", "docx-icon.emf", 965200, 609600),
  /** `progId` for an embedded PowerPoint 2007+ (.pptx) document. */
  PPTX: new ProgIdMember("PPTX", "PowerPoint.Show.12", "pptx-icon.emf", 965200, 609600),
  /** `progId` for an embedded Excel 2007+ (.xlsx) document. */
  XLSX: new ProgIdMember("XLSX", "Excel.Sheet.12", "xlsx-icon.emf", 965200, 609600),
};
export const PROG_ID = Object.freeze(
  Object.assign(
    function PROG_ID(v: unknown): ProgIdMember {
      const m = Object.values(PROG_ID_MEMBERS).find((m) => m === v || m.value === v);
      if (!m) throw new ValueError(`${typeof v === "string" ? `'${v}'` : String(v)} is not a valid PROG_ID`);
      return m;
    },
    PROG_ID_MEMBERS,
    // members are instances of PROG_ID (python `isinstance(PROG_ID.XLSX, PROG_ID)`)
    { prototype: ProgIdMember.prototype },
  ),
);
export type PROG_ID = ProgIdMember;
''',
}


def ts_str(s):
    return json.dumps(s, ensure_ascii=False)


def gen_module(modname):
    mod = importlib.import_module(f"pptx.enum.{modname}")
    out = [
        f"// GENERATED by scripts/gen_enums.py from python-pptx's pptx/enum/{modname}.py. Do not edit.",
        f"// {(mod.__doc__ or '').strip().splitlines()[0]}",
    ]
    needs_value_error = modname in EXTRA
    imports = set()
    body = []
    classes = [
        obj
        for k, obj in vars(mod).items()
        if inspect.isclass(obj)
        and obj.__module__ == mod.__name__
        and issubclass(obj, (BaseEnum, BaseXmlEnum))
        and k == obj.__name__
    ]
    for cls in classes:
        is_xml = issubclass(cls, BaseXmlEnum)
        base = "BaseXmlEnum" if is_xml else "BaseEnum"
        imports.add(base)
        doc = inspect.getdoc(cls) or ""
        body.append("")
        body.append("/**")
        for line in doc.splitlines():
            body.append(f" * {line}".rstrip().replace("*/", "*\\/"))
        body.append(" */")
        body.append(f'export const {cls.__name__} = defineEnum("{cls.__name__}", {base}, {{')
        for name, member in cls.__members__.items():
            docstr = (member.__doc__ or "").strip()
            if is_xml:
                body.append(f"  {name}: [{member.value}, {ts_str(member.xml_value)}, {ts_str(docstr)}],")
            else:
                body.append(f"  {name}: [{member.value}, {ts_str(docstr)}],")
        body.append("});")
        body.append(f"export type {cls.__name__} = {base};")
        for alias, obj in vars(mod).items():
            if obj is cls and alias != cls.__name__:
                body.append(f"export const {alias} = {cls.__name__};")
                body.append(f"export type {alias} = {base};")
    out.append(f'import {{ {", ".join(sorted(imports))}, defineEnum }} from "./base.js";')
    if needs_value_error:
        out.append('import { ValueError } from "../errors.js";')
    out.extend(body)
    if modname in EXTRA:
        out.append(EXTRA[modname].rstrip())
    return "\n".join(out) + "\n"


def main():
    outdir = sys.argv[1]
    for m in MODULES:
        with open(f"{outdir}/{m}.ts", "w", encoding="utf-8", newline="\n") as f:
            f.write(gen_module(m))
        print(f"{outdir}/{m}.ts")


if __name__ == "__main__":
    main()
