// Generate src/templates/data.ts from the files in src/templates/ (python-pptx's
// pptx/templates): XML templates as strings, binaries as base64.
// Usage: node scripts/gen_templates.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "templates");
const text = {};
const binary = {};
for (const f of fs.readdirSync(dir).sort()) {
  const p = path.join(dir, f);
  if (f.endsWith(".ts")) continue;
  if (f.endsWith(".xml")) text[f.slice(0, -4)] = fs.readFileSync(p, "utf8");
  else binary[f] = fs.readFileSync(p).toString("base64");
}
let out = "// GENERATED by scripts/gen_templates.mjs from python-pptx's pptx/templates. Do not edit.\n";
out += "export const TEXT: Record<string, string> = " + JSON.stringify(text, null, 1) + ";\n";
out += "export const BINARY: Record<string, string> = " + JSON.stringify(binary, null, 1) + ";\n";
fs.writeFileSync(path.join(dir, "..", "src", "templates", "data.ts"), out);
console.log("templates:", Object.keys(text).length, "xml,", Object.keys(binary).length, "binary");
