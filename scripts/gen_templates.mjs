// Generate src/templates/data.ts and src/templates/icons.ts from the files in templates/
// (python-pptx's pptx/templates): XML templates as strings, binaries as base64. The OLE icons
// (*.emf, about 360 KB of base64) go to icons.ts, which only the `@gljeremy/pptx-ts/ole-icons` entry
// imports, so browser bundles don't carry them unless they embed OLE objects.
// Usage: node scripts/gen_templates.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "templates");
const text = {};
const binary = {};
const icons = {};
for (const f of fs.readdirSync(dir).sort()) {
  const p = path.join(dir, f);
  if (f.endsWith(".xml")) text[f.slice(0, -4)] = fs.readFileSync(p, "utf8");
  else if (f.endsWith(".emf")) icons[f] = fs.readFileSync(p).toString("base64");
  else binary[f] = fs.readFileSync(p).toString("base64");
}
const head = "// GENERATED by scripts/gen_templates.mjs from python-pptx's pptx/templates. Do not edit.\n";
let out = head;
out += "export const TEXT: Record<string, string> = " + JSON.stringify(text, null, 1) + ";\n";
out += "export const BINARY: Record<string, string> = " + JSON.stringify(binary, null, 1) + ";\n";
fs.writeFileSync(path.join(dir, "..", "src", "templates", "data.ts"), out);
out = head + "// The OLE object icons, base64. Imported only by src/ole-icons.ts.\n";
out += "export const ICONS: Record<string, string> = " + JSON.stringify(icons, null, 1) + ";\n";
fs.writeFileSync(path.join(dir, "..", "src", "templates", "icons.ts"), out);
console.log("templates:", Object.keys(text).length, "xml,", Object.keys(binary).length, "binary,", Object.keys(icons).length, "icons");
