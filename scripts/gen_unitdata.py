"""Generate test/oxml/unitdata/*.ts from python-pptx's tests/oxml/unitdata builders.

The builders are declarative (`__tag__`, `__nspfxs__`, `__attrs__`, an optional `__init__`
taking the tag) plus `a_xxx()` factory functions, so they translate mechanically.

Usage: python scripts/gen_unitdata.py <python-pptx checkout> test/oxml/unitdata
"""
import ast
import json
import re
import sys


def camel(name):
    return re.sub(r"_+([A-Za-z0-9])", lambda m: m.group(1).upper(), name)


def lit(n):
    return ast.literal_eval(n)


for mod in ("dml", "shape", "text"):
    tree = ast.parse(open(f"{sys.argv[1]}/tests/oxml/unitdata/{mod}.py", encoding="utf-8").read())
    out = [f"// GENERATED by scripts/gen_unitdata.py from python-pptx tests/oxml/unitdata/{mod}.py.",
           'import { BaseBuilder } from "../../unitdata.js";', ""]
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            out.append(f"export class {node.name} extends BaseBuilder {{")
            for st in node.body:
                if isinstance(st, ast.Assign) and st.targets[0].id in ("__tag__", "__nspfxs__", "__attrs__"):
                    v = lit(st.value)
                    out.append(f"  static {st.targets[0].id} = {json.dumps(list(v) if isinstance(v, tuple) else v)};")
            for st in node.body:
                if isinstance(st, ast.FunctionDef) and st.name == "__init__":
                    params = [a.arg for a in st.args.args[1:]]
                    out.append(f"  constructor({', '.join(p + ': ' + ('string' if p == 'tag' else 'string[]') for p in params)}) {{")
                    out.append("    super();")
                    if "tag" in params:
                        out.append("    this._tag = tag;")
                    if "nspfxs" in params:
                        out.append("    this._nspfxs = [...nspfxs];")
                    out.append("  }")
                elif isinstance(st, ast.FunctionDef) and st.name.startswith("with_"):
                    # explicit with_x(self, v): self._set_xmlattr("<attr>", v); return self
                    attr = st.body[0].value.args[0].value
                    out.append(f"  {camel(st.name)}(value: any): this {{")
                    out.append(f'    this._setXmlattr("{attr}", value);')
                    out.append("    return this;")
                    out.append("  }")
            out.append("}")
            out.append("")
        elif isinstance(node, ast.FunctionDef):
            ret = node.body[-1].value
            args = ", ".join(json.dumps(list(lit(a))) if isinstance(a, ast.Tuple) else json.dumps(lit(a)) for a in ret.args)
            out.append(f"export const {node.name} = (): any => new {ret.func.id}({args});")
            if camel(node.name) != node.name:
                out.append(f"export const {camel(node.name)} = {node.name};")
    open(f"{sys.argv[2]}/{mod}.ts", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print(mod)
