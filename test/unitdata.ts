// Hand port of python-pptx tests/unitdata.py: the base class for XML data builders used by
// some unit tests. Subclasses set static `__tag__`, `__nspfxs__` and `__attrs__`; every
// attribute in `__attrs__` gets a `with<Name>(value)` method (python's `with_<name>()`).
import { parseXml } from "../src/oxml/parser.js";
import { nsdecls } from "../src/oxml/ns.js";

const camel = (s: string) => s.replace(/_+([A-Za-z0-9])/g, (_m, c: string) => c.toUpperCase());

export class BaseBuilder {
  static __tag__ = "";
  static __nspfxs__: string[] = [];
  static __attrs__: string[] = [];

  _empty = false;
  _nsdecls = "";
  _text = "";
  _xmlattrs: string[] = [];
  _xmlattrMethodMap: Record<string, string> = {};
  _childBldrs: BaseBuilder[] = [];

  constructor() {
    for (const attrName of this.__attrs__) {
      const baseName = attrName.includes(":") ? attrName.split(":")[1] : attrName;
      this._xmlattrMethodMap[camel(`with_${baseName}`)] = attrName;
    }
    // python's __getattr__: generalized "with_{xmlattr_name}()" methods
    return new Proxy(this, {
      get(target, prop, recv) {
        if (typeof prop === "string" && !(prop in target) && prop in target._xmlattrMethodMap) {
          return (value: any) => {
            target._setXmlattr(target._xmlattrMethodMap[prop], value);
            return recv;
          };
        }
        return Reflect.get(target, prop, recv);
      },
    });
  }

  get __tag__(): string {
    return (this.constructor as typeof BaseBuilder).__tag__;
  }
  get __nspfxs__(): string[] {
    return (this.constructor as typeof BaseBuilder).__nspfxs__;
  }
  get __attrs__(): string[] {
    return (this.constructor as typeof BaseBuilder).__attrs__;
  }

  /** Element parsed from XML generated by builder in current state */
  get element(): any {
    return parseXml(this.xml());
  }

  withChild(childBldr: BaseBuilder): this {
    this._childBldrs.push(childBldr);
    return this;
  }

  withNsdecls(...nspfxs: string[]): this {
    if (!nspfxs.length) nspfxs = this.__nspfxs__;
    this._nsdecls = ` ${nsdecls(...nspfxs)}`;
    return this;
  }

  xml(indent = 0): string {
    const indentStr = " ".repeat(indent);
    if (this._isEmpty) return `${indentStr}${this._emptyElementTag}\n`;
    return `${this._nonEmptyElementXml(indent)}\n`;
  }

  get _emptyElementTag(): string {
    return `<${this.__tag__}${this._nsdecls}${this._xmlattrsStr}/>`;
  }

  get _endTag(): string {
    return `</${this.__tag__}>`;
  }

  get _isEmpty(): boolean {
    return this._childBldrs.length === 0 && this._text.length === 0;
  }

  _nonEmptyElementXml(indent: number): string {
    const indentStr = " ".repeat(indent);
    if (this._text) return `${indentStr}${this._startTag}${this._text}${this._endTag}`;
    let xml = `${indentStr}${this._startTag}\n`;
    for (const c of this._childBldrs) xml += c.xml(indent + 2);
    return xml + `${indentStr}${this._endTag}`;
  }

  _setXmlattr(xmlattrName: string, value: any): void {
    this._xmlattrs.push(` ${xmlattrName}="${String(value)}"`);
  }

  get _startTag(): string {
    return `<${this.__tag__}${this._nsdecls}${this._xmlattrsStr}>`;
  }

  get _xmlattrsStr(): string {
    return this._xmlattrs.join("");
  }
}
